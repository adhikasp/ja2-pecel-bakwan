def arc(who, x0, y0, x1, y1, lift, n=12):
    out = ""
    for i in range(1, n):
        t = i / n
        x = x0 + (x1 - x0) * t
        y = y0 + (y1 - y0) * t - lift * t * (1 - t)
        out += f'\t<div class="dot arc" data-anchor="{who}" data-dx="{x:.0f}" data-dy="{y:.0f}"></div>\n'
    return out



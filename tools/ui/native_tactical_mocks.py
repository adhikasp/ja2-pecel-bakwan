def box(cls, x, y, w, h):
    return f'\t<div class="tgt {cls}" style="left: {x}dp; top: {y}dp; width: {w}dp; height: {h}dp;"></div>\n'


def pocket_targets(free_vest=(2, 3)):
    out = "".join(box("", x, y, 130, 58) for x, y in HANDS)

def cur(tone, name, legacy, icon=None, sm=None, ring=False, pips=0, dm=False):
    p = ""
    if ring:
        p += '<div class="rt"></div>'
    if icon:
        p += f'<img class="icon" src="icon-{icon}"/>'
    if sm:
        p += f'<img class="icon sm" src="icon-{sm}"/>'
    for i in range(pips):
        p += f'<div class="pip" style="left: {70 + i * 10}dp;"></div>'
    if dm:
        p += '<div class="dm"></div>'
    return f'<div class="cur {tone}"><div class="pic">{p}</div><span class="n">{name}</span><span class="s">{legacy}</span></div>'



FOOT = "</div>\n</body>\n</rml>\n"


def write(name, title, body):
    with open(os.path.join(OUT, name + ".rml"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEAD.format(t=title) + body + FOOT)



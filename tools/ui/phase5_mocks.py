"""Writes the Phase 5 wireframes of the native tactical HUD (M2, docs/ui/tactical.md) to
assets/ui/mocks/phase5/*.rml. The style is assets/ui/mocks/phase5/tactical.rcss (hand written).

The mocks are shown in the game over the real tactical world (tests/e2e/manual/phase5_mocks.lua):
- data-world="clear" on <body> hides the legacy HUD, so the whole world shows behind the mock;
- data-anchor="<merc>" puts the names, bars and menus over that merc in the world (MockWorld.cc);
- item pictures and faces come from the player's game data at an integer scale (nitem-, nitembig-, sface-).

Run it after changing the mock data or layout:  python tools/ui/phase5_mocks.py
"""

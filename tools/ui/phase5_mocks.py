def world_overlays(combat=False, sel=SELECTED, damage=None, target=False, path=None):
    out = []
    for m in MERCS:
        name, hp, hpmax, en, ap = m[0], m[3], m[4], m[5], m[7]
        c = "ov ov-merc" + (" sel" if name == sel else "")
        apv = f'<span class="apv">{ap} AP</span>' if combat and name == sel else ""
        out.append(f'<div class="{c} audit-skip" data-anchor="{name}" data-dy="-6"><span class="nm">{name}</span>'
                   f'<div class="bars"><div class="bar hp"><div class="fill" style="width: {hp * 100 // hpmax}%"></div></div>'
                   f'<div class="bar breath"><div class="fill" style="width: {en}%"></div></div></div>{apv}</div>')
    if damage:
        who, n = damage
        out.append(f'<div class="ov ov-dmg audit-skip" data-anchor="{who}" data-dx="44" data-dy="-36">&#8722;{n}</div>')
    if target:
        out.append('<div class="ov ov-target audit-skip" data-anchor="enemy0" data-dy="-30" title="Chance to hit, AP cost">'
                   '<img class="icon" src="icon-target"/><span class="k">Hit</span><span>62%</span><span class="k">AP</span><span>4</span></div>')
    if path:
        who, txt = path
        out.append(f'<div class="ov ov-path audit-skip" data-anchor="{who}" data-dx="150" data-dy="40">{txt}</div>')
    return "\n\t".join(out)



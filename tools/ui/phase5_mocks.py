def log_lines(lines=LOG):
    out = []
    for i, (tm, _ic, tx, cls) in enumerate(lines):
        old = " old" if i == 0 and len(lines) > 2 else ""
        out.append(f'<div class="log-line {cls}{old}"><span class="tm">{tm}</span><span class="tx">{e(tx)}</span></div>')
    return f'<div class="log-lines audit-skip" id="tac.log.lines" title="Recent messages (L opens the log)">{"".join(out)}</div>'



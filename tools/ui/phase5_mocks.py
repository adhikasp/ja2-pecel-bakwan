def slot(item=None, cls="", lbl="", count=None, cond=None, ghost="face-gear", big=False, sid="", title="", att=False, x=2):
    c = "slot" + (" big" if big else "") + (" " + cls if cls else "")
    i = f' id="{sid}"' if sid else ""
    t = f' title="{title}"' if title else ""
    if item is None:
        inner = f'<img class="ghost" src="icon-{ghost}"/>'
    else:
        inner = f'<div class="item">{pic("nitem", item, x)}</div>'
        if count:
            inner += f'<span class="count">{count}</span>'
        if cond is not None:
            worn = " worn" if cond < 60 else ""
            inner += f'<div class="cond{worn}"><div class="fill" style="height: {cond}%"></div></div>'
        if att:
            inner += '<img class="att" src="icon-add" title="Has attachments"/>'
    if lbl:
        inner += f'<span class="lbl">{lbl}</span>'
    return f'<div class="{c}"{i}{t}>{inner}</div>'



def e(s):
    return s.replace("&", "&amp;").replace("&amp;#", "&#")


def pic(kind, n, x=2, cls="pic"):
    """A game picture at an integer scale (MockWorld.cc sizes it): kind is nitem, nitembig or sface."""
    xs = "" if x == 2 else f' data-x="{x}"'
    return f'<img class="{cls}" src="{kind}-{n}"{xs}/>'


def doc(name, title, body, world=True, extra_rcss=""):
    w = ' data-world="clear"' if world else ""
    return f"""<rml>
<head>
	<title>{title} (Phase 5 wireframe)</title>
	<link type="text/rcss" href="../../components.rcss"/>
	<link type="text/rcss" href="tactical.rcss"/>{extra_rcss}
</head>
<!-- M2 wireframe of the native tactical HUD (docs/ui/tactical.md), shown over the real tactical world.
     Literal data. Generated by tools/ui/phase5_mocks.py: edit the generator, not this file. -->
<body class="t5"{w}>
<div class="t5-root" id="tac">
{body}
</div>
</body>
</rml>
"""



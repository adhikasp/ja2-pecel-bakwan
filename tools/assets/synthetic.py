PCX_SIZE = (640, 480)

# The placeholder frame size: one opaque pixel.
#
# A sheet's header size is a nominal bounds, not the frame — a 64-frame civ death sheet is 640x480
# nominal and 21x45 per frame, the single-frame credits backdrop is 642x482 nominal and 640x480 per
# frame — and the real per-frame size is not in the manifest. Code blits a frame into a surface the
# same size as the real frame (the credits backdrop fills a 640x480 scratch surface; the merc popup
# border tiles strips of a 10x4 frame), so a frame larger than the real one writes past the surface
# it draws into. One pixel is smaller than every real frame, which makes the placeholder safe
# wherever the frame lands; what a screen looks like is not what these runs assert.
PLACEHOLDER_FRAME = (1, 1)


def placeholder(w: int, h: int, seed: int) -> tuple[bytes, bytes]:
    """A fully opaque (w, h) image: a diagonal ramp, so two files differ but each run does not."""
    idx = bytearray(w * h)
    for y in range(h):
        row = y * w
        for x in range(w):
            idx[row + x] = (seed + x + y) & 0xFF
    return bytes(idx), b"\x01" * (w * h)


def aux_data(frames: int) -> bytes:
    """AuxObjectData per sub-image (HImage.h), as the animation sheets carry it: 16 bytes each, and
    only the first sub-image of a direction holds `ubNumberOfFrames` (= frames per direction) with
    the flag the original sheets set. LoadAnimationSurface reads that count and checks the app data
    is exactly 16 bytes per sub-image, so a sheet without it throws.

    A soldier/civilian sheet has eight directions, and its frame count is a multiple of eight; a
    sheet that is not (a vehicle, a monster) is a single direction."""
    per_dir = frames // 8 if frames % 8 == 0 else frames
    out = bytearray()
    for i in range(frames):
        entry = bytearray(16)
        if i % per_dir == 0:
            entry[8] = per_dir & 0xFF
            entry[9] = 2
        out += entry
    return bytes(out)


def sti_bytes(asset: dict, seed: int) -> bytes:
    w, h = asset.get("size") or PCX_SIZE
    frames = max(1, asset.get("frames") or 1)
    fw, fh = PLACEHOLDER_FRAME
    frames_data = []
    for i in range(frames):
        idx, mask = placeholder(fw, fh, seed + i)
        frames_data.append((fw, fh, 0, 0, idx, mask))
    aux = aux_data(frames) if asset.get("category") in ("animation", "effect") else b""
    return sti.build_indexed(frames_data, PALETTE, aux, size=(w, h))


def pcx_bytes(asset: dict, seed: int) -> bytes:
    w, h = PCX_SIZE
    idx, _ = placeholder(w, h, seed)
    return pcx.build(w, h, idx, PALETTE)


def font_bytes(seed: int) -> bytes:
    """An ETRLE font: one small opaque glyph per sub-image, so text advances and prints at a
    readable position. The text registry records the string, not the pixels, so assertions on text
    do not depend on the glyphs looking like letters."""
    idx, mask = placeholder(FONT_GLYPH_W, FONT_GLYPH_H, seed)
    frames = [(FONT_GLYPH_W, FONT_GLYPH_H, 0, 0, idx, mask) for _ in range(FONT_FRAMES)]
    return sti.build_indexed(frames, PALETTE, size=(640, 480))


def ja2set_dat_bytes() -> bytes:
    """The tileset database, as InitEngineTilesets (WorldDat.cc) reads it: a uint8 tileset count, a
    uint32 tile-type count, then per tileset a 32-byte name, a uint8 ambience id and 151 32-byte
    surface filenames. It validates both counts and throws otherwise, so zeros will not do; the
    names are empty, which is a tileset of no surfaces (the world is slice 4)."""
    num_tilesets = 50   # VANILLA_NUM_TILESETS (World_Tileset_Enums.h)
    num_files = 151     # NUMBEROFTILETYPES (TileDat.h)
    body = bytearray(1 + 4)
    body[0] = num_tilesets
    struct.pack_into("<I", body, 1, num_files)
    body += bytes(num_tilesets * (32 + 1 + num_files * 32))
    return bytes(body)


def _profile_offsets() -> dict[str, int]:
    """The byte offset of every field of the 716-byte merc profile record.

    Derived from ExtractMercProfile's own field order (LoadSaveMercProfile.cc) rather than written
    out by hand; the parsed record's size is asserted, so a layout change in C++ fails the generator
    instead of silently writing the wrong bytes."""
    text = MERC_PROFILE_CC.read_text(encoding="utf-8")
    body = re.sub(r"//[^\n]*", "", re.search(r"void ExtractMercProfile\(.*?\n\}", text, re.S).group(0))
    scalars = {"U8": 1, "I8": 1, "BOOL": 1, "U16": 2, "I16": 2, "U32": 4, "I32": 4}
    arrays = {
        "bBuddy": (5, 1), "bHated": (5, 1), "usApproachFactor": (4, 2), "ubRoomRangeStart": (2, 1),
        "usStatChangeChances": (12, 2), "usStatChangeSuccesses": (12, 2), "ubRoomRangeEnd": (2, 1),
        "ubApproachVal": (4, 1), "ubApproachMod": (12, 1), "bMercOpinion": (75, 1),
        "bHatedTime": (5, 1), "bHatedCount": (5, 1),
    }
    offsets, offset = {}, 0
    for line in (l.strip() for l in body.splitlines()):
        m = re.match(r"EXTR_(U8|I8|U16|I16|U32|I32|BOOL)\(S,\s*([^)]+)\)", line)
        if m:
            offsets.setdefault(m.group(2).strip(), offset)
            offset += scalars[m.group(1)]
            continue
        m = re.match(r"EXTR_SKIP\(S,\s*(\d+)\)", line)
        if m:
            offset += int(m.group(1))
            continue
        m = re.match(r"EXTR_(U8A|I8A|U16A|I16A|U32A|I32A)\(S,\s*([^,]+),\s*([^)]+)\)", line)
        if m:
            target = m.group(2).strip()
            key = target.lstrip("*").removeprefix("p.")
            count, size = ((19, scalars[m.group(1)[:-1]]) if key == "bin"
                           else (arrays[key][0], arrays[key][1]))
            offsets.setdefault(target, offset)
            offset += count * size
            continue
        m = re.match(r"p\.(\w+) = S\.readString\((\w+)\)", line)
        if m:
            offsets["p." + m.group(1)] = offset
            offset += {"NAME_LENGTH": NAME_LENGTH, "NICKNAME_LENGTH": NICKNAME_LENGTH}[m.group(2)] * 2
            continue
        m = re.match(r"p\.(\w+) = S\.readUTF8\((\w+),", line)
        if m:
            offsets["p." + m.group(1)] = offset
            offset += 30      # PaletteRepID_LENGTH
    if offset != PROFILE_SIZE:
        raise ValueError(f"the parsed profile layout is {offset} bytes, not {PROFILE_SIZE}")
    return offsets


def _load_jsonc(path: Path):
    """The .json files under assets/externalized/ carry // and /* */ comments."""
    text = path.read_text(encoding="utf-8")
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    text = re.sub(r",\s*([}\]])", r"\1", text)
    return json.loads(text)


def profile_display_names() -> dict[int, str]:
    """A deterministic display name per profile: the compiled roster's internal name in title case
    ("BARRY" -> "Barry").

    prof.dat is where the game's merc names come from — MercProfile::deserializeStruct falls back to
    the binary profile's zName/zNickname whenever mercs-profile-info.json names no fullName or
    nickname, which is every profile — so a stub cannot leave them empty: the tests (and the A.I.M.
    list they click) say "Barry" and "Grunty", and state().mercs reports what the profile holds."""
    roster = _load_jsonc(ROSTER) if ROSTER.is_file() else []
    names = {}
    for entry in roster:
        pid = int(entry["profileID"])
        internal = entry.get("internalName")
        names[pid] = internal.replace("_", " ").title() if internal else f"Profile {pid:03d}"
    return names


def _write_utf16_fixed(buf: bytearray, offset: int, text: str, chars: int) -> None:
    """A text field of `chars` UTF-16 code units at `offset`, NUL terminated (the rest stays zero)."""
    raw = text[:chars - 1].encode("utf-16-le")
    buf[offset:offset + len(raw)] = raw


# The .edt files the game reads as fixed-width tables (EDT.h): rows of these column widths. A
# placeholder row carries readable text so a screen that lists the file (the credits reel, the help
# pages) has something to show; LoadEncryptedData's ROT-1 round-trips printable ASCII.
EDT_ROW_LAYOUT = {
    "help.edt": [640], "credits.edt": [80], "aimhist.edt": [400], "alumname.edt": [80],
    "alumni.edt": [80, 560], "aimpol.edt": [400], "insurancesingle.edt": [80],
    "insurancemulti.edt": [400], "imptext.edt": [400], "flowercard.edt": [400],
    "flowerdesc.edt": [80, 80, 320],
}
EDT_GENERIC_TEXT = "Synthetic game data for the e2e suite. "


def _edt_encode(text: str) -> bytes:
    """LoadEncryptedData's ROT-1, inverted: a character above 33 is stored one up."""
    return b"".join(
        ((ord(c) + 1) if ord(c) > 33 else ord(c)).to_bytes(2, "little") for c in text)


def edt_bytes(name: str, size: int) -> bytes:
    """A placeholder for one .edt. A table file gets a text row per record (the credits file's first
    row is the heading the native screen looks for); anything else is filled with the generic text,
    so every read is a readable, non-empty string."""
    body = bytearray(size)
    cols = EDT_ROW_LAYOUT.get(name)
    if not cols:
        text = _edt_encode(EDT_GENERIC_TEXT * (size // 2 // len(EDT_GENERIC_TEXT) + 1))
        body[:len(text)] = text[:size]
        return bytes(body)
    row_len = sum(cols)
    for row in range(size // (row_len * 2)):
        text = (f"@T;Synthetic {name}" if row == 1 and name == "credits.edt"
                else f"Synthetic line {row:03d}")
        raw = _edt_encode(text)
        body[row * row_len * 2:row * row_len * 2 + len(raw)] = raw
    return bytes(body)


def prof_stats() -> bytes:
    """A generic merc's stats, as (field, format, value) — the bytes a profile needs to be a merc at
    all. A zero bExpLevel divides by zero on the map screen (MapScreen.cc DrawCharStats), a merc with
    no life is dead, and the rest are what the screens read for their bars and the roster."""
    stats = {
        "bLifeMax": ("i8", 100), "bLife": ("i8", 100), "bExpLevel": ("i8", 3),
        "bStrength": ("i8", 70), "bAgility": ("i8", 70), "bDexterity": ("i8", 70),
        "bWisdom": ("i8", 70), "bMarksmanship": ("i8", 70), "bMedical": ("i8", 70),
        "bMechanical": ("i8", 70), "bExplosive": ("i8", 70), "bLeadership": ("i8", 70),
        "sExpLevelGain": ("i16", 55), "sAgilityGain": ("i16", 40), "sDexterityGain": ("i16", 40),
        "sWisdomGain": ("i16", 40), "sMarksmanshipGain": ("i16", 40), "sMedicalGain": ("i16", 40),
        "sMechanicGain": ("i16", 40), "sExplosivesGain": ("i16", 40), "sLeadershipGain": ("i16", 40),
        "sStrengthGain": ("i16", 40),
        "uiBlinkFrequency": ("u32", 3000), "uiExpressionFrequency": ("u32", 1000),
        "uiWeeklySalary": ("u32", 1200), "uiBiWeeklySalary": ("u32", 2400),
        "sSalary": ("i16", 1200), "bMercStatus": ("i8", 0),
    }
    offsets = _profile_offsets()
    codes = {"u8": "B", "i8": "b", "u16": "H", "i16": "h", "u32": "I", "i32": "i"}
    out = bytearray(PROFILE_SIZE)
    for field, (kind, value) in stats.items():
        struct.pack_into("<" + codes[kind], out, offsets["p." + field], value)
    return bytes(out)


def prof_dat_bytes() -> bytes:
    """The 170 profiles, encoded so JA2EncryptedFileRead decodes them back: a display name and a
    generic stat block, which is what the compiled roster does not supply.

    BinaryProfileData::deserialize reads one profile per call, and the cipher's state (last byte and
    rotation index) is local to each call: every 716-byte block is encoded independently."""
    names = profile_display_names()
    stats = prof_stats()
    out = bytearray()
    for pid in range(PROFILES):
        plain = bytearray(stats)
        name = names.get(pid, f"Profile {pid:03d}")
        _write_utf16_fixed(plain, 0, name, NAME_LENGTH)
        _write_utf16_fixed(plain, NAME_LENGTH * 2, name, NICKNAME_LENGTH)
        last = 0
        for i, b in enumerate(plain):
            v = (b + last + ROTATION[i % len(ROTATION)]) & 0xFF
            out.append(v)
            last = v
    return bytes(out)


def npc_script_files(control_path: Path = SCRIPT_RECORDS_CONTROL) -> list[str]:
    """The npcdata/*.npc files loadAllScriptRecords opens: script-records-control.json names them."""
    if not control_path.is_file():
        return []
    ctrl = json.loads(control_path.read_text(encoding="utf-8"))
    names = {ctrl["fileNameForScriptControlledPCs"]}
    for meanwhile in ctrl.get("meanwhiles", []):
        for char in meanwhile.get("chars", []):
            names.add(char["fileName"])
    return [f"npcdata/{n}" for n in sorted(names)]


def all_non_image_files() -> list[str]:
    """Everything that is not one of the manifest's images: the initial abort (prof.dat), the
    eagerly-loaded fonts, and the script records loadAllScriptRecords reads."""
    return NON_IMAGE_FILES + npc_script_files() + [SYNTHETIC_MARKER]


def used_assets(manifest: dict) -> list[dict]:
    """The images to emit: the 300 of the usage tour, plus the explicit extras."""
    wanted = {p.lower() for p in EXTRA_IMAGES}
    return [a for a in manifest["assets"] if "usage" in a or a["path"].lower() in wanted]


def build_files(manifest: dict) -> tuple[dict[str, dict[str, bytes]], dict[str, bytes]]:
    """Returns (archives, loose): archive name -> entry path -> bytes, and Data-relative loose files."""
    archives: dict[str, dict[str, bytes]] = {}
    loose: dict[str, bytes] = {}
    emitted = set()
    for n, asset in enumerate(used_assets(manifest)):
        path, archive = asset["path"], asset["archive"]
        emitted.add(path.lower())
        seed = n * 7 + 1
        if path.lower().endswith(".pcx"):
            content = pcx_bytes(asset, seed)
        else:
            content = sti_bytes(asset, seed)
        if archive == "(loose)":
            loose[path] = content
        else:
            lib = ARCHIVE_LIB_PATHS[archive]
            if not path.lower().startswith(lib.lower()):
                raise ValueError(f"{path} is not under {archive}'s library path {lib!r}")
            archives.setdefault(archive, {})[path[len(lib):]] = content
    missing = [p for p in EXTRA_IMAGES if p.lower() not in emitted]
    if missing:
        raise ValueError(f"EXTRA_IMAGES not found in the manifest: {missing}")
    for i, name in enumerate(FONT_FILES):
        archives.setdefault("Fonts.slf", {})[name] = font_bytes(1000 + i)
    archives.setdefault("Binarydata.slf", {})["prof.dat"] = prof_dat_bytes()
    archives["Binarydata.slf"]["ja2set.dat"] = ja2set_dat_bytes()
    for name, size in BINARYDATA_FILES.items():
        archives["Binarydata.slf"][name] = (edt_bytes(name, size) if name.endswith(".edt")
                                            else bytes(size))
    for name, (num_lights, num_rays) in DATA_ROOT_FILES.items():
        body = bytearray(2 + 6 * num_lights + 2 + 2 * num_rays)
        struct.pack_into("<H", body, 0, num_lights)
        struct.pack_into("<H", body, 2 + 6 * num_lights, num_rays)
        archives.setdefault("Data.slf", {})[name] = bytes(body)
    # A zero-filled quote table: every field is read and clamped (ExtractNPCQuoteInfoArrayFromFile),
    # and an NPC with no quotes is the state a sector without them is in.
    zero_npc = bytes(NPC_QUOTE_RECORDS * NPC_RECORD_SIZE)
    for path in npc_script_files():
        loose[path] = zero_npc
    loose[SYNTHETIC_MARKER] = MARKER_TEXT.encode("utf-8")
    return archives, loose


def generate(out_dir: Path, manifest_path: Path = DEFAULT_MANIFEST, quiet: bool = False) -> dict:
    """Writes <out_dir>/Data/ and returns a small summary. A stale Data/ is removed first."""
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    data = out_dir / "Data"
    if data.exists():
        for child in sorted(data.rglob("*"), reverse=True):
            child.unlink() if child.is_file() else child.rmdir()
        data.rmdir()
    data.mkdir(parents=True)
    archives, loose = build_files(manifest)
    for name, entries in sorted(archives.items()):
        write_slf(data / name, name.upper(), ARCHIVE_LIB_PATHS[name], entries)
    for path, content in sorted(loose.items()):
        target = data / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
    summary = {
        "images": len(used_assets(manifest)),
        "archives": {n: len(e) for n, e in sorted(archives.items())},
        "loose": sorted(loose),
        "data": str(data),
    }
    if not quiet:
        total = sum(sum(len(c) for c in e.values()) for e in archives.values()) + sum(map(len, loose.values()))
        print(f"{summary['images']} placeholder images in {len(archives)} archives -> {data} "
              f"({total / 1e6:.1f} MB)")
        for n, c in summary["archives"].items():
            print(f"  {n}: {c}")
        print(f"  loose: {', '.join(summary['loose'])}")
    return summary


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, required=True, help="directory to write Data/ into")
    ap.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)
    generate(args.out, args.manifest, args.quiet)
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Generates a synthetic Data/ tree, so the behavioural e2e suite runs with no game install (issue #302).

    python tools/assets/synthetic.py --out _bin/synthetic        # writes <out>/Data/

The game reads its resources through the VFS: every *.slf in Data/ is a layer, plus the loose files
beside them, and assets/externalized/ (copied next to the binary by cmake) supplies all the JSON. A
Data/ of placeholders therefore boots the real game, and `ctest -L '^e2e-synthetic$'` drives it in
CI, where there is no Steam install.

What it emits, and where each part of the list comes from:

  * The **300 images on 9 screens** of the usage tour — `assets/manifest.json`'s `usage` array, the
    committed output of tests/spike/asset_usage_tour.lua — plus EXTRA_IMAGES, the handful of images
    that load before a tour installs its hook or on a screen the tour never opens. Each is written
    into the same archive (or as the same loose file) the real install keeps it in, with the real
    file's header size and frame count.
  * The **16 fonts** InitializeFonts loads eagerly and unguarded (src/game/Utils/Font_Control.cc).
    They are 188-frame ETRLE sheets: the translation table maps codepoints to glyph indices up to
    187, so every glyph the game can ask for exists.
  * **binarydata/prof.dat** — the first hard abort of a partial Data/ (DefaultContentManager.cc
    loadGameData) and where a merc's display name comes from. 170 vanilla profiles x 716 bytes, each
    with a name and a generic stat block, encoded with JA2's own rotation cipher so
    JA2EncryptedFileRead decodes them back.
  * The rest of NON_IMAGE_FILES: the non-image files boot and the screens read — the tileset
    database, the light templates, the .npc quote tables and the string tables.
  * A **SYNTHETIC marker** at the root of Data/, surfaced as ja2.state().dataSource so a log line or
    a screenshot says which data a run used (the false-green guard).

The output is deterministic — fixed palette, fixed geometry, no timestamps — and gitignored: it is
generated data, not content, and no original art is copied. See tests/e2e/golden/README.md for why
the golden resolution suite stays on a real install, and issue #302 for what still needs real data
(the world: maps, the tileset names they load, and the battles over them).
"""

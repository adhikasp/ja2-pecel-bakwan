# A synthetic palette: a deterministic ramp, so nothing here is anyone's artwork.
PALETTE = [(i, (i * 5) % 256, (i * 11) % 256) for i in range(256)]

# A screen-filling placeholder for the PCX backgrounds, which the manifest has no size for (they are
